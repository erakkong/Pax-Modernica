compiled_provinces = []
for spec in PROVINCE_SPECS:
    src_type, src_key = spec["geom_source"]
    geom = None
    
    if src_type == "nuts":
        feat = nuts_by_id.get(src_key)
        if feat:
            geom = feat["geometry"]
    elif src_type == "admin1":
        feat = admin1_data.get(src_key)
        if feat:
            geom = feat["geometry"]
    elif src_type == "admin1_merge":
        geom = merge_admin1_geoms(src_key)
    elif src_type == "custom_is_west":
        geom = {"type": "Polygon", "coordinates": [is_west_pts]}
    elif src_type == "custom_is_east":
        geom = {"type": "Polygon", "coordinates": [is_east_pts]}
        
    if not geom:
        print(f"Warning: geometry not found for {spec['id']} ({src_type}:{src_key})")
        continue
        
    svg_path = geom_to_svg_path(geom)
    centroid = compute_centroid(geom)
    
    compiled_prov = {
        "id": spec["id"],
        "name": spec["name"],
        "city": spec.get("city", spec["name"].split("(")[-1].rstrip(")")),
        "region_id": spec["region_id"],
        "owner_id": spec["owner_id"],
        "center": centroid,
        "svg_path": svg_path,
        "terrain": spec["terrain"],
        "is_coastal": spec["is_coastal"],
        "population": spec["population"],
        "tax_revenue": spec["tax_revenue"],
        "goods_produced": spec["goods_produced"],
        "religion": spec["religion"],
        "culture": spec["culture"],
        "buildings": {
            "barracks": 1 if spec["fortification_level"] >= 2 else 0,
            "fort": max(0, spec["fortification_level"] - 1),
            "port": 1 if spec["is_coastal"] else 0,
            "administration": spec["infrastructure_level"],
        },
        "infrastructure_level": spec["infrastructure_level"],
        "fortification_level": spec["fortification_level"],
        "neighbors": []
    }
    compiled_provinces.append(compiled_prov)

print(f"Successfully compiled {len(compiled_provinces)} provinces.")

output_data = {
    "viewBox": f"0 0 {WIDTH} {HEIGHT}",
    "projection": "Albers Equal-Area Conic (Europe EPSG:3035)",
    "province_count": len(compiled_provinces),
    "provinces": compiled_provinces
}


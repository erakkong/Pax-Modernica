# Helper to merge multiple cantons / admin1 regions into a single MultiPolygon
def merge_admin1_geoms(keys):
    coords = []
    for k in keys:
        feat = admin1_data.get(k)
        if not feat:
            continue
        geom = feat["geometry"]
        if geom["type"] == "Polygon":
            coords.append(geom["coordinates"])
        elif geom["type"] == "MultiPolygon":
            coords.extend(geom["coordinates"])
    return {"type": "MultiPolygon", "coordinates": coords}

